"""Write the `embeds.xml` (or `.toc` lines) an addon needs for the Kits and parts it uses.

    python3 -m tooling.package.embeds eventKit timerKit
    python3 -m tooling.package.embeds moduleKit eventKit/Coalescing --root 'Libs\\MoltenCodes-Custom'
    python3 -m tooling.package.embeds settingsKit --toc
    python3 -m tooling.package.embeds settingsKit --out embeds.xml
    python3 -m tooling.package.embeds --footprint

An addon author names what they use: a Kit ID selects its core, ``ID/Part``
one of its parts (and the core), ``ID/*`` every part. The command resolves
every dependency, and every part a dependency's contract names, and prints one
``<Script file="..."/>`` line per file in load order, each file once, under
``--root`` (the folder the author copies the bundle to, ``Libs\\MoltenCodes-Custom``
by default, which is where ``python3 -m tooling.package.build`` with the same
selection and ``--out Libs`` puts it). ``--toc`` prints the same files as
``.toc`` lines instead, for an addon that lists its files in its ``.toc``.

The selection and the load order are the builder's own (`tooling.package.build.select`
and `tooling.package.parts`), and ``build --embeds`` writes its ``embeds.xml``
with `render_embeds_xml`, so the generated file and the bundle never disagree.

``--footprint`` prints the two tables `docs/EMBEDDING.md` carries between
generated markers ("Minimum footprint per Kit" and "Optional parts"), which
repository validation holds to the manifests.
"""

from __future__ import annotations

import argparse
import re
import sys
from pathlib import Path
from typing import Any, Sequence

from tooling.package import build
from tooling.package import parts as kit_parts
from tooling.validation.validate_manifests import is_development


#: The folder an author copies a custom bundle into, as their `.toc` spells it.
DEFAULT_ROOT = "Libs\\" + build.CUSTOM_BUNDLE_NAME

#: One loader line of an `embeds.xml`.
SCRIPT_RE = re.compile(r'<Script\s+file="([^"]+)"\s*/>')

#: The namespace every World of Warcraft UI file declares.
UI_NAMESPACE = "http://www.blizzard.com/wow/ui/"

#: The markers around each generated block of `docs/EMBEDDING.md`.
FOOTPRINT_BLOCK = "footprint"
PARTS_BLOCK = "parts"


def client_path(root: str, bundle_path: str) -> str:
    """Join ``root`` and a POSIX bundle path into the backslashed path the client reads."""
    pieces = [piece for piece in root.replace("/", "\\").split("\\") if piece]
    pieces.extend(bundle_path.split("/"))
    return "\\".join(pieces)


def render_embeds_xml(load_order: Sequence[str], description: str, root: str = "") -> str:
    """Return an `embeds.xml` loading ``load_order`` (POSIX bundle paths) under ``root``.

    Paths in an `.xml` file are relative to the file itself, so the
    `embeds.xml` the builder writes into a bundle root uses an empty
    ``root``, and one at an addon's own root uses the bundle folder.
    """
    lines = [
        f'<Ui xmlns="{UI_NAMESPACE}">',
        "    <!--",
        f"        Generated by tooling.package.embeds for: {description}.",
        "        Do not reorder: every file loads after the files it needs.",
        "        Regenerate it instead of editing it when the selection changes.",
        "    -->",
    ]
    lines.extend(f'    <Script file="{client_path(root, path)}" />' for path in load_order)
    lines.append("</Ui>")
    return "\n".join(lines) + "\n"


def render_toc_lines(load_order: Sequence[str], description: str, root: str) -> str:
    """Return the `.toc` lines loading ``load_order`` under ``root``, with a comment."""
    lines = [
        f"# MoltenCodes, generated by tooling.package.embeds for: {description}.",
        "# Keep these lines first and in this order.",
    ]
    lines.extend(client_path(root, path) for path in load_order)
    return "\n".join(lines) + "\n"


def listed_scripts(text: str) -> list[str]:
    """Return the files an `embeds.xml` loads, in order, as POSIX paths."""
    return [reference.replace("\\", "/") for reference in SCRIPT_RE.findall(text)]


def selection_from_selectors(
    manifests: dict[str, dict[str, Any]], selectors: Sequence[str]
) -> build.Selection:
    """Turn ``ID``, ``ID/Part`` and ``ID/*`` selectors into the builder's selection."""
    packages: list[str] = []
    part_selectors: list[str] = []
    for text in selectors:
        selector = kit_parts.parse_selector(text)
        if selector is None:
            raise build.BuildError(
                f'"{text}" is not a Kit or a part; write <packageId>, <packageId>/<Part> '
                "or <packageId>/*"
            )
        if selector.part is None:
            packages.append(selector.package)
        else:
            part_selectors.append(text.strip())
    return build.select(manifests, packages=packages, part_selectors=part_selectors)


# Documentation tables ----------------------------------------------------------


def footprint_rows(manifests: dict[str, dict[str, Any]]) -> list[tuple[int, list[str], list[str]]]:
    """Return ``(files, kits, alongside)`` rows of the minimum-footprint table.

    For each package, the Kits its core needs: ``files`` counts one per Kit
    including Registry, ``alongside`` names the Kits other than Registry and
    the package itself, in load order. Packages sharing both are one row.
    Rows are ordered by file count, then by where the Kits alongside load,
    and each row's Kits by where they load.
    """
    grouped: dict[tuple[int, tuple[str, ...]], list[str]] = {}
    for name in sorted(manifests):
        if name == "registry":
            continue
        closure = build.packages_in_order(kit_parts.closure_nodes(kit_parts.Node(name), manifests))
        alongside = tuple(package for package in closure if package not in ("registry", name))
        grouped.setdefault((len(closure), alongside), []).append(name)

    order = build.packages_in_order(kit_parts.all_nodes(manifests, sorted(manifests)))
    position = {name: index for index, name in enumerate(order)}
    rows = [
        (files, sorted(kits, key=lambda kit: position[kit]), list(alongside))
        for (files, alongside), kits in grouped.items()
    ]
    rows.sort(key=lambda row: (row[0], [position[kit] for kit in row[2]], position[row[1][0]]))
    return rows


def kit_cell(name: str, manifests: dict[str, dict[str, Any]]) -> str:
    """Return a Kit's name as a table cell, marked when it is never bundled."""
    if is_development(manifests[name]):
        return f"`{name}` (development only)"
    return f"`{name}`"


def render_footprint_table(manifests: dict[str, dict[str, Any]]) -> str:
    """Return the "Minimum footprint per Kit" table of `docs/EMBEDDING.md`."""
    lines = [
        "| Files | Kit | Alongside `registry/Registry.lua` |",
        "|---|---|---|",
    ]
    for files, kits, alongside in footprint_rows(manifests):
        names = ", ".join(kit_cell(kit, manifests) for kit in kits)
        needs = ", ".join(f"`{kit}`" for kit in alongside) or "nothing"
        lines.append(f"| {files} | {names} | {needs} |")

    further = [
        name
        for name in sorted(manifests)
        if len(build.runtime_files(name)) > 1
    ]
    if further:
        lines.append("")
        lines.append(
            "Each Kit counts as one file here. "
            + " ".join(
                f"`{name}` also carries {len(build.runtime_files(name)) - 1} further core files "
                f"under {further_directories(name)}."
                for name in further
            )
        )
    return "\n".join(lines) + "\n"


def further_directories(name: str) -> str:
    """Name the directories of a package's further core files: ``apiKit/flavours/``."""
    directories = sorted({relative.rsplit("/", 1)[0] for relative in build.runtime_files(name)[1:]})
    return ", ".join(f"`{name}/{directory}/`" for directory in directories)


def render_parts_table(manifests: dict[str, dict[str, Any]]) -> str:
    """Return the "Optional parts" table of `docs/EMBEDDING.md`.

    One row per part: its selector, its file, what it adds and the other
    Kits and parts it brings in beyond its own core.
    """
    rows: list[str] = []
    for name in sorted(manifests):
        for part, entry in kit_parts.part_entries(manifests[name]).items():
            node = kit_parts.Node(name, part)
            core_closure = set(kit_parts.closure_nodes(kit_parts.Node(name), manifests))
            brings = [
                need.label
                for need in kit_parts.closure_nodes(node, manifests)
                if need != node and need not in core_closure
            ]
            needs = ", ".join(f"`{label}`" for label in brings) or "nothing"
            rows.append(
                f"| `{node.label}` | `{name}/{build.part_runtime_file(name, part)}` "
                f"| {entry.get('description', '')} | {needs} |"
            )
    if not rows:
        return "No Kit has optional parts yet: every Kit is its core file.\n"
    header = [
        "| Part | File | Adds | Brings in beyond its Kit |",
        "|---|---|---|---|",
    ]
    return "\n".join(header + rows) + "\n"


def generated_block(name: str, body: str) -> str:
    """Return ``body`` between the begin and end markers of the block called ``name``."""
    return f"<!-- generated:{name} -->\n{body}<!-- /generated:{name} -->\n"


def read_generated_block(text: str, name: str) -> str | None:
    """Return the text between a block's markers in ``text``, or ``None`` when absent."""
    begin = f"<!-- generated:{name} -->\n"
    end = f"<!-- /generated:{name} -->"
    start = text.find(begin)
    if start < 0:
        return None
    finish = text.find(end, start + len(begin))
    if finish < 0:
        return None
    return text[start + len(begin) : finish]


# Command line --------------------------------------------------------------------


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    """Parse the generator's command line."""
    parser = argparse.ArgumentParser(
        prog="python3 -m tooling.package.embeds",
        description="Write the embeds.xml (or .toc lines) for the Kits and parts an addon uses.",
    )
    parser.add_argument(
        "selectors",
        nargs="*",
        metavar="KIT[/PART]",
        help="a Kit ID (its core), ID/Part (one part) or ID/* (every part)",
    )
    parser.add_argument(
        "--root",
        default=DEFAULT_ROOT,
        help=f"the folder the bundle sits in, relative to the addon (default {DEFAULT_ROOT})",
    )
    parser.add_argument("--toc", action="store_true", help="print .toc lines instead of embeds.xml")
    parser.add_argument("--out", type=Path, metavar="FILE", help="write the result to FILE")
    parser.add_argument(
        "--footprint",
        action="store_true",
        help="print the footprint and parts tables of docs/EMBEDDING.md instead",
    )
    arguments = parser.parse_args(argv)
    if not arguments.footprint and not arguments.selectors:
        parser.error("name at least one Kit or part, or pass --footprint")
    return arguments


def main(argv: Sequence[str] | None = None) -> int:
    """Entry point for ``python3 -m tooling.package.embeds``."""
    arguments = parse_args(argv)
    try:
        manifests = build.load_valid_manifests()
        if arguments.footprint:
            text = (
                generated_block(FOOTPRINT_BLOCK, render_footprint_table(manifests))
                + "\n"
                + generated_block(PARTS_BLOCK, render_parts_table(manifests))
            )
        else:
            selection = selection_from_selectors(manifests, arguments.selectors)
            load_order = build.load_order_paths(selection)
            description = build.describe_selection(selection)
            if arguments.toc:
                text = render_toc_lines(load_order, description, arguments.root)
            else:
                text = render_embeds_xml(load_order, description, arguments.root)
    except build.BuildError as failure:
        print(f"error: {failure}", file=sys.stderr)
        return 1

    if arguments.out is None:
        sys.stdout.write(text)
        return 0
    arguments.out.write_text(text, encoding="utf-8")
    print(arguments.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
