local TestEnv = require("PanelKitTestEnv")

describe("PanelKit bootstrap", function()
  after_each(TestEnv.Reset)

  it("publishes through Registry", function()
    local PanelKit, _, _, _, Registry = TestEnv.NewPackage()
    local registered, revision = Registry:Get("panelKit", 1)
    assert.are.equal(PanelKit, registered)
    assert.are.equal(PanelKit.REVISION, revision)
  end)

  it("returns the same facade on a duplicate embedded load and keeps its panels", function()
    local PanelKit = TestEnv.NewPackage()
    local panel = PanelKit:Register("MyAddon")
    local reloaded = TestEnv.ReloadPackage()
    assert.are.equal(PanelKit, reloaded)
    assert.are.equal(panel, reloaded:Get("MyAddon"))
  end)

  it("does not reinterpret private state owned by a newer compatible revision", function()
    local PanelKit, _, _, _, Registry = TestEnv.NewPackage()
    local shippedRevision = PanelKit.REVISION
    local upgraded, previous = Registry:Register("panelKit", 1, 99)
    assert.are.equal(PanelKit, upgraded)
    assert.are.equal(shippedRevision, previous)

    rawset(PanelKit, "REVISION", 99)
    rawset(PanelKit, "_state", { schema = 999 })
    package.loaded["PanelKit"] = nil
    local reloaded = require("PanelKit")
    assert.are.equal(PanelKit, reloaded)
    assert.are.equal(99, reloaded.REVISION)
  end)

  it("upgrades in place: panels, limits and canvases registered before run the new code", function()
    local PanelKit, settings, WidgetKit, OptionsKit = TestEnv.NewPackage()
    TestEnv.DefineTree(OptionsKit, "MyAddon")
    local panel = PanelKit:Register("MyAddon")
    PanelKit:SetLimits({ maxPanels = 100 })
    panel:Open()
    local shownRendering = panel:GetRendering()

    local nextRevision = PanelKit.REVISION + 1
    local upgraded = TestEnv.LoadRevision(nextRevision)
    assert.are.equal(PanelKit, upgraded)
    assert.are.equal(nextRevision, upgraded.REVISION)
    assert.are.equal(panel, upgraded:Get("MyAddon"))
    assert.are.equal(100, upgraded:GetLimits().maxPanels)
    assert.are.equal(shownRendering, panel:GetRendering())

    -- The canvas Blizzard holds keeps its scripts, which now reach the new
    -- revision's code through the shared dispatch table.
    settings.Close()
    assert.are.equal(0, WidgetKit:GetStatistics().active)
    panel:Open()
    assert.is_not_nil(panel:GetRendering())
    assert.are.equal("MyAddon", panel:GetName())
  end)

  it("refuses shared state whose limit holds an invalid value", function()
    local PanelKit = TestEnv.NewPackage()
    rawset(PanelKit._state.limits, "maxPanels", 0)
    TestEnv.expectErrorContaining("package state is corrupted or incomplete", function()
      TestEnv.ReloadPackage()
    end)
  end)

  it("requires Registry", function()
    TestEnv.Reset()
    TestEnv.InstallWowApi()
    local ok, value = pcall(require, "PanelKit")
    assert.is_false(ok)
    assert.is_truthy(tostring(value):find("Registry API 2", 1, true))
  end)

  it("requires WidgetKit", function()
    TestEnv.Reset()
    TestEnv.InstallWowApi()
    require("Registry")
    require("SignalKit")
    require("SchemaKit")
    require("OptionsKit")
    local ok, value = pcall(TestEnv.requireAfterFailedLoad, "PanelKit")
    assert.is_false(ok)
    assert.is_truthy(tostring(value):find("WidgetKit API 1", 1, true))
  end)

  it("requires WidgetKit's Renderer part", function()
    TestEnv.Reset()
    TestEnv.InstallWowApi()
    require("Registry")
    require("SignalKit")
    require("SchemaKit")
    require("OptionsKit")
    require("WidgetKit")
    local ok, value = pcall(TestEnv.requireAfterFailedLoad, "PanelKit")
    assert.is_false(ok)
    assert.is_truthy(tostring(value):find("WidgetKit API 1 with its Renderer part", 1, true))
  end)

  it("requires OptionsKit", function()
    TestEnv.Reset()
    TestEnv.InstallWowApi()
    require("Registry")
    require("SignalKit")
    require("WidgetKit")
    for _, part in ipairs({ "Containers", "Text", "Button", "CheckBox", "Slider", "EditBox" }) do
      require("WidgetKit-" .. part)
    end
    for _, part in ipairs({ "Dropdown", "ColorPicker", "Renderer" }) do
      require("WidgetKit-" .. part)
    end
    local ok, value = pcall(TestEnv.requireAfterFailedLoad, "PanelKit")
    assert.is_false(ok)
    assert.is_truthy(tostring(value):find("OptionsKit API 1", 1, true))
  end)

  it("refuses an incomplete facade left by an earlier failed load", function()
    TestEnv.Reset()
    TestEnv.InstallWowApi()
    local Registry = require("Registry")
    require("SignalKit")
    require("SchemaKit")
    require("OptionsKit")
    require("WidgetKit")
    Registry:Register("panelKit", 1, 1)
    local ok, value = pcall(TestEnv.requireAfterFailedLoad, "PanelKit")
    assert.is_false(ok)
    assert.is_truthy(tostring(value):find("MoltenCodes PanelKit", 1, true))
  end)
end)
