local TestEnv = require("BarKitTestEnv")

describe("BarKit bars", function()
  local BarKit
  before_each(function()
    BarKit = TestEnv.NewPackage()
    TestEnv.InstallHostErrorHandler()
  end)
  after_each(TestEnv.Reset)

  it("acquires a shown status bar at its default size, texture and colours", function()
    local bar = BarKit:Acquire()
    local frame = bar:GetFrame()
    assert.is_true(frame:IsObjectType("StatusBar"))
    assert.is_true(frame:IsShown())
    assert.are.equal(TestEnv.GetGlobal("UIParent"), frame:GetParent())
    assert.are.same({ 200, 18 }, { frame:GetWidth(), frame:GetHeight() })
    assert.are.equal(
      "Interface\\TargetingFrame\\UI-StatusBar",
      frame:GetStatusBarTexture():GetTexture()
    )
    assert.are.same({ 0.2, 0.6, 1, 1 }, { frame:GetStatusBarColor() })
    assert.is_false(frame.icon:IsShown())
    assert.are.equal("BarKit.Bar", getmetatable(bar))
  end)

  it("takes its size, texture and parent from the options", function()
    local parent = TestEnv.GetGlobal("CreateFrame")("Frame")
    local bar = BarKit:Acquire({ width = 120, height = 12, texture = 1234, parent = parent })
    local frame = bar:GetFrame()
    assert.are.same({ 120, 12 }, { frame:GetWidth(), frame:GetHeight() })
    assert.are.equal(1234, frame:GetStatusBarTexture():GetTexture())
    assert.are.equal(parent, frame:GetParent())
  end)

  it("shows a status value in its range, and labels, icon and colours", function()
    local bar = BarKit:Acquire({ height = 16 })
    bar:SetMinMax(0, 250)
    bar:SetValue(125)
    bar:SetLabel("Health")
    bar:SetValueText(125)
    bar:SetIcon(136243)
    bar:SetColor(0, 1, 0)
    bar:SetBackgroundColor(0.1, 0.1, 0.1, 0.8)
    local frame = bar:GetFrame()
    assert.are.same({ 0, 250 }, { frame:GetMinMaxValues() })
    assert.are.equal(125, frame:GetValue())
    assert.are.equal("Health", frame.label:GetText())
    assert.are.equal("125", frame.valueText:GetText())
    assert.is_true(frame.icon:IsShown())
    assert.are.equal(136243, frame.icon:GetTexture())
    assert.are.same({ 16, 16 }, { frame.icon:GetWidth(), frame.icon:GetHeight() })
    assert.are.same({ 0, 1, 0, 1 }, { frame:GetStatusBarColor() })
    assert.are.equal(0.8, frame.background.colorAlpha)
    bar:SetIcon(nil)
    assert.is_false(frame.icon:IsShown())
    bar:SetLabel(nil)
    assert.is_nil(frame.label:GetText())
  end)

  it("passes secret values and ranges to the status bar untouched", function()
    TestEnv.InstallSecretProbe()
    local secret, maximum = TestEnv.NewSecret(), TestEnv.NewSecret()
    local bar = BarKit:Acquire()
    bar:SetMinMax(0, maximum)
    bar:SetValue(secret)
    local frame = bar:GetFrame()
    assert.are.equal(secret, frame:GetValue())
    assert.are.equal(maximum, select(2, frame:GetMinMaxValues()))
  end)

  it("refuses a secret text unless allowSecret, and draws it with it", function()
    TestEnv.InstallSecretProbe()
    local secret = TestEnv.NewSecret()
    local bar = BarKit:Acquire()
    TestEnv.expectErrorContaining(
      "BarKit.Bar:SetLabel text must not be a secret value; pass { allowSecret = true } to draw one",
      function()
        bar:SetLabel(secret)
      end
    )
    bar:SetLabel(secret, { allowSecret = true })
    bar:SetValueText(secret, { allowSecret = true })
    assert.are.equal(secret, bar:GetFrame().label:GetText())
    assert.are.equal(secret, bar:GetFrame().valueText:GetText())
  end)

  it("gives a released bar back cleared and hands the same frame out again", function()
    local bar = BarKit:Acquire()
    bar:SetLabel("old")
    bar:SetValueText("old")
    bar:SetIcon(1)
    bar:SetMinMax(0, 10)
    bar:SetValue(5)
    bar:Start(30)
    local frame = bar:GetFrame()
    BarKit:Release(bar)
    assert.is_false(frame:IsShown())
    assert.is_nil(frame:GetScript("OnUpdate"))
    assert.is_nil(frame.label:GetText())
    assert.is_nil(frame.valueText:GetText())
    assert.is_nil(frame.icon:GetTexture())
    assert.are.equal(0, frame:GetValue())
    TestEnv.expectErrorContaining("must be called on an acquired BarKit bar", function()
      bar:SetLabel("late")
    end)
    TestEnv.expectErrorContaining("BarKit:Release bar must be an acquired BarKit bar", function()
      BarKit:Release(bar)
    end)
    local again = BarKit:Acquire()
    assert.are.equal(frame, again:GetFrame())
    assert.is_false(again:IsRunning())
    assert.are.equal(1, BarKit._state.pool:GetCreatedCount())
  end)
end)
