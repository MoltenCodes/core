-- Argument errors, their stack levels and secret values. Each case calls the
-- public surface on one line and checks that the message names that line of
-- this file: a read through the facade's `__index`, a write through its
-- `__newindex`, the namespace entry, every method, and the helpers that raise
-- a Kit's refusal again.
local TestEnv = require("AddonKitTestEnv")

local assertRaisesInside = TestEnv.ExpectRaisedInside

describe("AddonKit arguments", function()
  after_each(TestEnv.Reset)

  ---A full package, a secret probe and MyAddon's facade.
  ---@return MoltenCodesFacade
  ---@return table AddonKit
  local function setUp()
    local AddonKit = TestEnv.NewFullPackage()
    TestEnv.InstallSecretProbe()
    return TestEnv.Namespace():For("MyAddon"), AddonKit
  end

  it("raises a facade read and write at the reading or writing line", function()
    local MC = setUp()
    local namespace = TestEnv.Namespace()
    assertRaisesInside("has no Kit or helper named Nope", function()
      return MC.Nope
    end)
    assertRaisesInside("TimerKit (API 1), which is not loaded", function()
      return MC.TimerKit
    end)
    assertRaisesInside("MC has no member of type number", function()
      return MC[1]
    end)
    assertRaisesInside("keep db on your addon object", function()
      MC.db = 1
    end)
    assertRaisesInside("keep <number> on your addon object", function()
      MC[2] = 1
    end)
    assertRaisesInside("MoltenCodes:For is called with a colon", function()
      namespace.For("MyAddon")
    end)
    assertRaisesInside("addonName must be the addon's folder name", function()
      namespace:For("")
    end)
    assertRaisesInside("addonName must be the addon's folder name", function()
      namespace:For()
    end)
    assertRaisesInside("addonName must not be a secret value", function()
      namespace:For(TestEnv.NewSecret())
    end)
    assertRaisesInside("is called with a colon", function()
      namespace.For(TestEnv.NewSecret(), "A")
    end)
  end)

  it("raises method argument errors at the caller's line", function()
    local MC = setUp()
    local secret = TestEnv.NewSecret()
    assertRaisesInside("MC:NewAddon is called with a colon", function()
      MC.NewAddon()
    end)
    assertRaisesInside("MC:NewAddon is called with a colon", function()
      MC.NewAddon(secret)
    end)
    assertRaisesInside("MC:NewAddon definition must be", function()
      MC:NewAddon(5)
    end)
    assertRaisesInside("MC:NewAddon definition must be", function()
      MC:NewAddon(secret)
    end)
    assertRaisesInside("MC:NewModule name must be a non-empty string", function()
      MC:NewModule(5)
    end)
    assertRaisesInside("MC:NewModule name must not be a secret value", function()
      MC:NewModule(secret)
    end)
    assertRaisesInside("MC:NewModule definition must be", function()
      MC:NewModule("Bags", "x")
    end)
    assertRaisesInside("MC:GetModule name must be a non-empty string", function()
      MC:GetModule()
    end)
    assertRaisesInside("MC:GetAddon is called with a colon", function()
      MC.GetAddon({})
    end)
    assertRaisesInside("MC:Use facadeName must be a non-empty string", function()
      MC:Use(nil, 1)
    end)
    assertRaisesInside("did you mean MC.TimerKit?", function()
      MC:Use("Timerkit", 1)
    end)
    assertRaisesInside("MC:Use generation must be a positive integer", function()
      MC:Use("TimerKit", 1.5)
    end)
    assertRaisesInside("MC:Use generation must not be a secret value", function()
      MC:Use("TimerKit", secret)
    end)
    assertRaisesInside("MC:Database savedVariable must be", function()
      MC:Database(nil, {})
    end)
    assertRaisesInside("MC:Database defaults must be a table", function()
      MC:Database("MyAddonDB", 1)
    end)
    assertRaisesInside("MC:Database defaults must be a table", function()
      MC:Database("MyAddonDB", secret)
    end)
    assertRaisesInside("MC:Database options must be a table", function()
      MC:Database("MyAddonDB", {}, 1)
    end)
    assertRaisesInside("MC.Range min, max and default must not be secret", function()
      MC.Range(secret, 1, 1)
    end)
    assertRaisesInside("MC.Enum values and default must not be secret", function()
      MC.Enum(secret, 1)
    end)
    assertRaisesInside("MC:Options tree must be", function()
      MC:Options(secret)
    end)
    assertRaisesInside("MC:Options settings must be a table", function()
      MC:Options({}, secret)
    end)
    assertRaisesInside("settings holds an unknown field", function()
      MC:Options({}, { [secret] = 1 })
    end)
    assertRaisesInside("MC:Launcher definition must be a table", function()
      MC:Launcher(secret)
    end)
    assertRaisesInside("MC:Launcher db must be a database", function()
      MC:Launcher({}, secret)
    end)
    assertRaisesInside("MC:Launcher field must not be a secret value", function()
      MC:Launcher({}, { Validate = print }, secret)
    end)
  end)

  it("checks the package facade's receivers and limits", function()
    local _, AddonKit = setUp()
    local secret = TestEnv.NewSecret()
    assertRaisesInside("AddonKit:GetCatalogue must be called on the AddonKit facade", function()
      AddonKit.GetCatalogue({})
    end)
    assertRaisesInside("AddonKit:GetLimits must be called on the AddonKit facade", function()
      AddonKit.GetLimits()
    end)
    assertRaisesInside("AddonKit:SetLimits limits must be a table", function()
      AddonKit:SetLimits(secret)
    end)
    assertRaisesInside("it accepts maxFacades", function()
      AddonKit:SetLimits({ maxAddons = 1 })
    end)
    assertRaisesInside("it accepts maxFacades", function()
      AddonKit:SetLimits({ [secret] = 1 })
    end)
    assertRaisesInside("limits.maxFacades must not be a secret value", function()
      AddonKit:SetLimits({ maxFacades = secret })
    end)
    assertRaisesInside("limits.maxFacades must be an integer from 1 to 4096", function()
      AddonKit:SetLimits({ maxFacades = 4097 })
    end)
  end)

  it("removes AddonKit's own position from a message it raises again", function()
    setUp()
    local state = rawget(TestEnv.Namespace().Registries[2]:Get("addonKit", 1), "_state")
    local strip = state.helpers.withoutPosition
    assert.are.equal("refused", strip("Interface/AddOns/X/Libs/addonKit/AddonKit.lua:12: refused"))
    assert.are.equal("refused", strip("...parts/AddonKit-Database.lua:7: refused"))
    assert.are.equal("Core.lua:3: refused", strip("Core.lua:3: refused"))
    local object = {}
    assert.are.equal(object, strip(object))
  end)

  it("raises an error object that is not a string as it is", function()
    local MC = setUp()
    local object = {}
    local container = MC.ModuleKit:ForAddon("MyAddon")
    local create = container.CreateModule
    rawset(container, "CreateModule", function()
      error(object)
    end)
    local ok, failure = pcall(function()
      MC:NewAddon()
    end)
    rawset(container, "CreateModule", create)
    assert.is_false(ok)
    assert.are.equal(object, failure)
  end)
end)
