local TestEnv = require("UnitFrameKitTestEnv")

describe("UnitFrameKit scanning", function()
  local UnitFrameKit
  before_each(function()
    UnitFrameKit = TestEnv.NewPackage()
  end)
  after_each(TestEnv.Reset)

  it("keeps a shown button by its unit attribute", function()
    local frame = TestEnv.UnitButton("CompactPartyFrameMember2", "party1")
    TestEnv.RunScan(UnitFrameKit)
    assert.are.equal(frame, UnitFrameKit:GetUnitFrame("party1"))
  end)

  it("appends unitsuffix and maps a raid pet the way the client does", function()
    TestEnv.SetUnits({ raidpet1 = "Pet", party1target = "Bob" })
    local pet = TestEnv.UnitButton("MyRaidPet", "raid1", { attributes = { unitsuffix = "pet" } })
    local target =
      TestEnv.UnitButton("MyPartyTarget", "party1", { attributes = { unitsuffix = "target" } })
    TestEnv.RunScan(UnitFrameKit)
    assert.are.equal(pet, UnitFrameKit:GetUnitFrame("raidpet1"))
    assert.are.equal(target, UnitFrameKit:GetUnitFrame("party1target"))
  end)

  it("names an unnamed frame through its parent's name and parent key", function()
    local partyFrame = TestEnv.Widget({ name = "PartyFrame" })
    local member =
      TestEnv.UnitButton(nil, "party1", { parent = partyFrame, parentKey = "MemberFrame1" })
    TestEnv.RunScan(UnitFrameKit)
    assert.are.equal(member, UnitFrameKit:GetUnitFrame("party1"))
    assert.are.equal(member, UnitFrameKit:GetUnitFrame("party1", { kinds = { "party" } }))
  end)

  it("skips frames it cannot name", function()
    TestEnv.UnitButton(nil, "party1")
    TestEnv.UnitButton(nil, "party1", { parentKey = "Member" })
    TestEnv.UnitButton(nil, "party1", { parent = TestEnv.Widget(), parentKey = "Member" })
    TestEnv.RunScan(UnitFrameKit)
    assert.is_nil(UnitFrameKit:GetUnitFrame("party1"))
  end)

  it("skips forbidden, hidden, non-button, unit-less and aura frames", function()
    TestEnv.UnitButton("Forbidden", "party1", { forbidden = true })
    TestEnv.UnitButton("Hidden", "party1", { visible = false })
    TestEnv.UnitButton("Empty", "")
    TestEnv.UnitButton("NoUnit")
    TestEnv.UnitButton("Aura", "party1", { attributes = { type = "cancelaura" } })
    local plain = TestEnv.Widget({ name = "PlainFrame", attributes = { unit = "party1" } })
    TestEnv.Widget({ objectType = "Button", name = "NoMethods", GetAttribute = false })
    TestEnv.RunScan(UnitFrameKit)
    assert.are.same({}, UnitFrameKit:GetUnitFrames("party1"))
    assert.is_truthy(plain)
  end)

  it("skips a hidden frame at scan time even when it shows later", function()
    local frame = TestEnv.UnitButton("Later", "party1", { visible = false })
    TestEnv.RunScan(UnitFrameKit)
    frame.visible = true
    assert.is_nil(UnitFrameKit:GetUnitFrame("party1"))
    TestEnv.RunScan(UnitFrameKit)
    assert.are.equal(frame, UnitFrameKit:GetUnitFrame("party1"))
  end)

  it("tolerates widgets without the optional methods", function()
    TestEnv.Widget({ objectType = "Button", IsForbidden = false, GetObjectType = false })
    TestEnv.UnitButton("NoVisibility", "party1", { IsVisible = false })
    local bare = TestEnv.UnitButton(nil, "party1", { GetName = false, GetParentKey = false })
    TestEnv.RunScan(UnitFrameKit)
    assert.is_nil(UnitFrameKit:GetUnitFrame("party1"))
    assert.is_truthy(bare)
    TestEnv.SetGlobal("EnumerateFrames", function(current)
      if current == nil then
        return 7
      end
      return nil
    end)
    TestEnv.RunScan(UnitFrameKit)
    assert.is_nil(UnitFrameKit:GetUnitFrame("party1"))
  end)

  it("visits at most scanFramesPerStep frames per client frame and resumes in place", function()
    UnitFrameKit:SetLimits({ scanFramesPerStep = 3 })
    local made = {}
    for index = 1, 7 do
      made[index] = TestEnv.UnitButton("Raid" .. index, "party1")
    end
    UnitFrameKit:GetUnitFrame("party1")
    TestEnv.VisitCount()
    TestEnv.Tick(0.016)
    assert.are.equal(3, TestEnv.VisitCount())
    assert.is_true(UnitFrameKit:IsScanning())
    TestEnv.Tick(0.016)
    assert.are.equal(3, TestEnv.VisitCount())
    TestEnv.Tick(0.016)
    assert.are.equal(1, TestEnv.VisitCount())
    assert.is_false(UnitFrameKit:IsScanning())
    assert.are.equal(7, #UnitFrameKit:GetUnitFrames("party1"))
    assert.are.equal(made[1], UnitFrameKit:GetUnitFrame("party1"))
  end)

  it("sees frames created while the scan runs", function()
    UnitFrameKit:SetLimits({ scanFramesPerStep = 2 })
    TestEnv.UnitButton("First", "party1")
    TestEnv.UnitButton("Second", "party1")
    TestEnv.UnitButton("Third", "party1")
    UnitFrameKit:Rescan()
    TestEnv.Tick(0.016)
    local late = TestEnv.UnitButton("Late", "party1")
    while UnitFrameKit:IsScanning() do
      TestEnv.Tick(0.016)
    end
    assert.are.equal(late, UnitFrameKit:GetUnitFrames("party1")[4])
  end)

  it("runs OnUpdate only while a scan is due or running", function()
    assert.are.equal(0, TestEnv.ActiveOnUpdateCount())
    UnitFrameKit:GetUnitFrame("party1")
    assert.are.equal(1, TestEnv.ActiveOnUpdateCount())
    TestEnv.Tick(0.016)
    assert.are.equal(0, TestEnv.ActiveOnUpdateCount())
    assert.is_false(UnitFrameKit:IsScanning())
  end)

  it("coalesces events into one scan a second later", function()
    UnitFrameKit:GetUnitFrame("party1")
    TestEnv.Tick(0.016)
    TestEnv.UnitButton("Joined", "party1")
    TestEnv.Emit("GROUP_ROSTER_UPDATE")
    TestEnv.Emit("PLAYER_REGEN_DISABLED")
    TestEnv.Emit("PLAYER_ENTERING_WORLD")
    TestEnv.Tick(0.5)
    assert.is_true(UnitFrameKit:IsScanning())
    assert.are.equal(0, TestEnv.VisitCount())
    TestEnv.Tick(0.6)
    assert.are.equal(1, TestEnv.VisitCount())
    assert.is_false(UnitFrameKit:IsScanning())
    assert.is_truthy(UnitFrameKit:GetUnitFrame("party1"))
  end)

  it("lets Rescan bring a waiting scan forward", function()
    UnitFrameKit:GetUnitFrame("party1")
    TestEnv.Tick(0.016)
    TestEnv.Emit("PLAYER_REGEN_ENABLED")
    TestEnv.Emit("INSTANCE_ENCOUNTER_ENGAGE_UNIT")
    UnitFrameKit:Rescan()
    TestEnv.UnitButton("Now", "party1")
    TestEnv.Tick(0.016)
    assert.is_false(UnitFrameKit:IsScanning())
    assert.is_truthy(UnitFrameKit:GetUnitFrame("party1"))
  end)

  it("queues exactly one more scan for requests during a scan", function()
    UnitFrameKit:SetLimits({ scanFramesPerStep = 1 })
    TestEnv.UnitButton("One", "party1")
    TestEnv.UnitButton("Two", "party1")
    UnitFrameKit:Rescan()
    TestEnv.Tick(0.016)
    UnitFrameKit:Rescan()
    TestEnv.Emit("GROUP_ROSTER_UPDATE")
    TestEnv.VisitCount()
    TestEnv.Tick(0.016)
    TestEnv.Tick(0.016)
    assert.is_true(UnitFrameKit:IsScanning())
    TestEnv.Tick(0.016)
    TestEnv.Tick(0.016)
    TestEnv.Tick(0.016)
    assert.is_false(UnitFrameKit:IsScanning())
    assert.are.equal(3, TestEnv.VisitCount())
  end)

  it("asks for a scan on UNIT_PET only for the player and group members", function()
    UnitFrameKit:GetUnitFrame("party1")
    TestEnv.Tick(0.016)
    TestEnv.Emit("UNIT_PET", "target")
    TestEnv.Emit("UNIT_PET", nil)
    assert.is_false(UnitFrameKit:IsScanning())
    TestEnv.Emit("UNIT_PET", "player")
    assert.is_true(UnitFrameKit:IsScanning())
    TestEnv.Tick(2)
    TestEnv.Emit("UNIT_PET", "party3")
    assert.is_true(UnitFrameKit:IsScanning())
    TestEnv.Tick(2)
    TestEnv.Emit("UNIT_PET", "raid12")
    assert.is_true(UnitFrameKit:IsScanning())
  end)

  it(
    "keeps at most maxFrames frames and reports the overflow once until the limit changes",
    function()
      UnitFrameKit:SetLimits({ maxFrames = 2 })
      TestEnv.UnitButton("One", "party1")
      TestEnv.UnitButton("Two", "party1")
      TestEnv.UnitButton("Three", "party1")
      TestEnv.RunScan(UnitFrameKit)
      assert.are.equal(2, #UnitFrameKit:GetUnitFrames("party1"))
      local reported = TestEnv.TakeReportedValues()
      assert.are.same(
        { "UnitFrameKit keeps at most 2 frames; raise maxFrames with UnitFrameKit:SetLimits" },
        reported
      )
      TestEnv.RunScan(UnitFrameKit)
      assert.are.same({}, TestEnv.TakeReportedValues())
      UnitFrameKit:SetLimits({ maxFrames = 3 })
      TestEnv.RunScan(UnitFrameKit)
      assert.are.equal(3, #UnitFrameKit:GetUnitFrames("party1"))
      assert.are.same({}, TestEnv.TakeReportedValues())
    end
  )

  it("keeps nothing without EnumerateFrames", function()
    TestEnv.UnitButton("Kept", "party1")
    TestEnv.RunScan(UnitFrameKit)
    TestEnv.SetGlobal("EnumerateFrames", nil)
    TestEnv.RunScan(UnitFrameKit)
    assert.is_nil(UnitFrameKit:GetUnitFrame("party1"))
  end)

  it("never scans without CreateFrame", function()
    TestEnv.SetGlobal("CreateFrame", nil)
    TestEnv.UnitButton("Kept", "party1")
    assert.is_nil(UnitFrameKit:GetUnitFrame("party1"))
    UnitFrameKit:Rescan()
    assert.is_false(UnitFrameKit:IsScanning())
  end)

  it("skips a frame the client says this code may not access, and keeps scanning", function()
    -- Retail's `CanBeAccessedInContext` answers false for an object tainted
    -- code may not touch; the stand-in raises on every read of such a frame.
    local restricted = TestEnv.UnitButton("RestrictedButton", "party1")
    restricted.CanBeAccessedInContext = function()
      return false
    end
    restricted.GetObjectType = function()
      error("attempt to access a restricted object", 0)
    end
    local secretAnswer = TestEnv.UnitButton("SecretAccessButton", "party1")
    TestEnv.InstallSecretProbe()
    local secret = TestEnv.NewSecret()
    secretAnswer.CanBeAccessedInContext = function()
      return secret
    end
    local kept = TestEnv.UnitButton("Kept", "party1")
    TestEnv.RunScan(UnitFrameKit)
    assert.are.same({}, TestEnv.TakeReportedValues())
    assert.are.same({ kept }, UnitFrameKit:GetUnitFrames("party1"))
  end)

  it("drops a scan that raises, reports it, and scans afresh later", function()
    local frame = TestEnv.UnitButton("Kept", "party1")
    local enumerate = TestEnv.GetGlobal("EnumerateFrames")
    TestEnv.SetGlobal("EnumerateFrames", function()
      error("enumeration failed", 0)
    end)
    TestEnv.RunScan(UnitFrameKit)
    assert.are.same({ "enumeration failed" }, TestEnv.TakeReportedValues())
    assert.are.equal(0, TestEnv.ActiveOnUpdateCount())
    TestEnv.SetGlobal("EnumerateFrames", enumerate)
    TestEnv.RunScan(UnitFrameKit)
    assert.are.equal(frame, UnitFrameKit:GetUnitFrame("party1"))
  end)

  it("stops its OnUpdate when called with nothing to do", function()
    UnitFrameKit:GetUnitFrame("party1")
    TestEnv.Tick(0.016)
    local eventFrame = rawget(UnitFrameKit._state, "eventFrame")
    eventFrame:SetScript("OnUpdate", rawget(UnitFrameKit._state, "scripts").OnUpdate)
    TestEnv.Tick(0.016)
    assert.are.equal(0, TestEnv.ActiveOnUpdateCount())
  end)
end)
