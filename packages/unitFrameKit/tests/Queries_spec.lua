local TestEnv = require("UnitFrameKitTestEnv")

describe("UnitFrameKit queries", function()
  local UnitFrameKit
  before_each(function()
    UnitFrameKit = TestEnv.NewPackage()
  end)
  after_each(TestEnv.Reset)

  it("answers nil before the first scan and starts one", function()
    TestEnv.UnitButton("CompactPartyFrameMember2", "party1")
    assert.is_nil(UnitFrameKit:GetUnitFrame("party1"))
    assert.is_true(UnitFrameKit:IsScanning())
    TestEnv.Tick(0.016)
    assert.is_truthy(UnitFrameKit:GetUnitFrame("party1"))
  end)

  it("finds a unit through any token naming it", function()
    local frame = TestEnv.UnitButton("CompactPartyFrameMember3", "party2")
    TestEnv.RunScan(UnitFrameKit)
    assert.are.equal(frame, UnitFrameKit:GetUnitFrame("target"))
    assert.are.same({ frame }, UnitFrameKit:GetUnitFrames("party2"))
  end)

  it("reads the unit attribute again, so a reassigned frame answers its new unit", function()
    local frame = TestEnv.UnitButton("SUFHeaderpartyUnitButton1", "party1")
    TestEnv.RunScan(UnitFrameKit)
    frame.attributes.unit = "party2"
    assert.is_nil(UnitFrameKit:GetUnitFrame("party1"))
    assert.are.equal(frame, UnitFrameKit:GetUnitFrame("party2"))
    frame.attributes.unit = nil
    assert.is_nil(UnitFrameKit:GetUnitFrame("party2"))
  end)

  it("drops a kept frame while it is hidden", function()
    local first = TestEnv.UnitButton("ElvUF_PartyGroup1UnitButton2", "party1")
    local second = TestEnv.UnitButton("CompactPartyFrameMember2", "party1")
    TestEnv.RunScan(UnitFrameKit)
    first.visible = false
    assert.are.equal(second, UnitFrameKit:GetUnitFrame("party1"))
    assert.are.same({ second }, UnitFrameKit:GetUnitFrames("party1"))
  end)

  it("answers nothing for a unit that does not exist", function()
    TestEnv.UnitButton("CompactPartyFrameMember2", "party4")
    TestEnv.RunScan(UnitFrameKit)
    assert.is_nil(UnitFrameKit:GetUnitFrame("party4"))
    assert.are.same({}, UnitFrameKit:GetUnitFrames("party4"))
  end)

  it("answers nothing without UnitIsUnit, and queries without UnitExists", function()
    local frame = TestEnv.UnitButton("CompactPartyFrameMember2", "party1")
    TestEnv.RunScan(UnitFrameKit)
    local unitIsUnit = TestEnv.GetGlobal("UnitIsUnit")
    TestEnv.SetGlobal("UnitIsUnit", nil)
    assert.is_nil(UnitFrameKit:GetUnitFrame("party1"))
    TestEnv.SetGlobal("UnitIsUnit", unitIsUnit)
    TestEnv.SetGlobal("UnitExists", nil)
    assert.are.equal(frame, UnitFrameKit:GetUnitFrame("party1"))
  end)

  it("returns a new array from every GetUnitFrames call", function()
    TestEnv.UnitButton("CompactPartyFrameMember2", "party1")
    TestEnv.RunScan(UnitFrameKit)
    local first, second = UnitFrameKit:GetUnitFrames("party1"), UnitFrameKit:GetUnitFrames("party1")
    assert.are_not.equal(first, second)
    assert.are.same(first, second)
    assert.are.same({}, rawget(UnitFrameKit._state, "rankScratch"))
  end)

  describe("nameplates", function()
    it("answers Blizzard's UnitFrame child of the plate, or the plate", function()
      local unitFrame = {}
      local plate = TestEnv.Widget({ UnitFrame = unitFrame })
      TestEnv.SetNamePlate("nameplate1", plate)
      assert.are.equal(unitFrame, UnitFrameKit:GetNamePlate("nameplate1"))
      local bare = TestEnv.Widget()
      TestEnv.SetNamePlate("nameplate2", bare)
      assert.are.equal(bare, UnitFrameKit:GetNamePlate("nameplate2"))
      local noMethods = { UnitFrame = unitFrame }
      TestEnv.SetNamePlate("nameplate3", noMethods)
      assert.are.equal(unitFrame, UnitFrameKit:GetNamePlate("nameplate3"))
    end)

    it("answers nil for no plate, a forbidden plate or no C_NamePlate", function()
      assert.is_nil(UnitFrameKit:GetNamePlate("nameplate9"))
      TestEnv.SetNamePlate("nameplate1", TestEnv.Widget({ forbidden = true, UnitFrame = {} }))
      assert.is_nil(UnitFrameKit:GetNamePlate("nameplate1"))
      TestEnv.SetGlobal("C_NamePlate", {
        GetNamePlateForUnit = function()
          error("not a nameplate token")
        end,
      })
      assert.is_nil(UnitFrameKit:GetNamePlate("party1"))
      TestEnv.SetGlobal("C_NamePlate", {})
      assert.is_nil(UnitFrameKit:GetNamePlate("nameplate1"))
      TestEnv.SetGlobal("C_NamePlate", nil)
      assert.is_nil(UnitFrameKit:GetNamePlate("nameplate1"))
    end)
  end)

  describe("limits", function()
    it("defaults, publishes and changes the limits", function()
      assert.are.same(
        { maxFrames = 512, scanFramesPerStep = 400, maxListeners = 64 },
        UnitFrameKit:GetLimits()
      )
      assert.are.equal(512, UnitFrameKit.MAX_FRAMES)
      assert.are.equal(4096, UnitFrameKit.FRAMES_CEILING)
      assert.are.equal(400, UnitFrameKit.SCAN_FRAMES_PER_STEP)
      assert.are.equal(4000, UnitFrameKit.SCAN_STEP_CEILING)
      assert.are.equal(64, UnitFrameKit.MAX_LISTENERS)
      assert.are.equal(512, UnitFrameKit.LISTENERS_CEILING)
      assert.are.equal(64, UnitFrameKit.MAX_PATTERNS)
      UnitFrameKit:SetLimits({ maxFrames = 4096, scanFramesPerStep = 4000, maxListeners = 512 })
      assert.are.same(
        { maxFrames = 4096, scanFramesPerStep = 4000, maxListeners = 512 },
        UnitFrameKit:GetLimits()
      )
      UnitFrameKit:SetLimits({ maxListeners = 1 })
      assert.are.equal(4096, UnitFrameKit:GetLimits().maxFrames)
      assert.are_not.equal(UnitFrameKit:GetLimits(), UnitFrameKit:GetLimits())
    end)
  end)
end)
